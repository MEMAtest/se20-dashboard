import { writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const network = require('../network-map.js');
const datasets = [];
for (const id of network.tubeLineIds) {
    const response = await fetch(`https://api.tfl.gov.uk/Line/${id}/Route/Sequence/all`, { signal: AbortSignal.timeout(15000) });
    if (!response.ok) throw new Error(`Tube topology unavailable: ${id}`);
    const raw = await response.json();
    if (raw.lineId !== id || !raw.orderedLineRoutes?.length) throw new Error(`Wrong or empty topology: ${id}`);
    const records = new Map([...raw.stations, ...raw.stopPointSequences.flatMap(s => s.stopPoint)].map(s => [s.id, s]));
    const stations = [...records.values()].map(s => Object.fromEntries(
        ['id', 'name', 'lat', 'lon', 'modes', 'icsId', 'topMostParentId', 'lines'].map(key => [key,
            key === 'lines' ? s.lines.map(l => ({ id: l.id })) : s[key]])));
    const orderedLineRoutes = raw.orderedLineRoutes.map(r => ({ naptanIds: r.naptanIds }));
    const ids = new Set(stations.map(s => s.id));
    if (stations.some(s => !network.networkStationReference(s)) || orderedLineRoutes.some(r => r.naptanIds.some(s => !ids.has(s)))) {
        throw new Error(`Incomplete station references: ${id}`);
    }
    datasets.push({ definition: network.networkLines.find(l => l[0] === id), data: { lineId: id, stations, orderedLineRoutes } });
}
const layout = network.schematicLayout(datasets);
if (layout.routes.length !== 11 || layout.stations.size < 270) throw new Error('Incomplete Tube network');
const bundle = { retrievedAt: new Date().toISOString(), source: 'https://api.tfl.gov.uk/Line/{id}/Route/Sequence/all', datasets };
await writeFile(new URL('../tube-network.js', import.meta.url), `// Generated by scripts/build-tube-network.mjs from TfL station topology. Not live service data.\n(function(root,factory){if(typeof module==='object'&&module.exports)module.exports=factory();else root.JourneyTubeNetwork=factory();})(typeof globalThis!=='undefined'?globalThis:this,function(){return ${JSON.stringify(bundle)};});\n`);
console.log(JSON.stringify({ lines: layout.routes.length, stations: layout.stations.size, retrievedAt: bundle.retrievedAt }));
